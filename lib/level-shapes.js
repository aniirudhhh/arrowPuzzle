export function levelShape(level, size) {
  const shape = shapes[level - 1];
  if (!shape) return null;
  const [name, rows] = shape;
  const cells = [];
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      if (
        rows[Math.floor((y * rows.length) / size)][
          Math.floor((x * 17) / size)
        ] === "#"
      )
        cells.push([x, y]);
    }
  }
  return { name, cells };
}
